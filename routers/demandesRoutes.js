const express=require('express');
const router=express.Router();
const demandeController=require('../controllers/demandeController');
const authMiddleware=require('../middleware/authMiddleware');
const roleMiddleware=require('../middleware/roleMiddleware');
router.post('/create',authMiddleware,demandeController.createDemande);
router.get('/client/demandes',authMiddleware,demandeController.geteDemandeForClient);
router.get('/pro/demandes',authMiddleware,roleMiddleware(['professionnel']),demandeController.geteDemandeForPro);
router.put('/pro/demandes/:id/status',authMiddleware,roleMiddleware(['professionnel','client']),demandeController.updateStatus);
router.put('/pro/offer/:id',authMiddleware,roleMiddleware(['professionnel']),demandeController.ProposerPrix);
router.get('/pro/:id',authMiddleware,roleMiddleware(['professionnel']),demandeController.getDemandeById);
router.get('/allDemandes',authMiddleware,roleMiddleware(['admin']),demandeController.getAllDemandes);
module.exports=router;